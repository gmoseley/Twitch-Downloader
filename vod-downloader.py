CLIPS_RETENTION_DAYS = 7


def purge_old_clips():
    cutoff = datetime.now() - timedelta(days=CLIPS_RETENTION_DAYS)
    with lock:
        stale = []
        for vid, job in jobs.items():
            if job.get("category") != "manual" or job.get("status") != "completed":
                continue
            ts = job.get("completed_at") or job.get("created_at")
            if not ts:
                continue
            try:
                dt = datetime.fromisoformat(ts)
            except ValueError:
                continue
            if dt < cutoff:
                stale.append(vid)
    for vid in stale:
        delete_job(vid)
    return len(stale)


