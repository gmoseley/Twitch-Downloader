PROGRESS_RE = re.compile(
    r"\[download\]\s+(?P<percent>[\d.]+)% of\s+~?(?P<size>[\d.]+\w+)"
    r"(?:\s+at\s+(?P<speed>[\d.]+\w+/s|Unknown))?"
    r"(?:\s+ETA\s+(?P<eta>[\d:]+|Unknown))?"
    r"(?:\s+\(frag\s+(?P<frag_done>\d+)/(?P<frag_total>\d+)\))?"
)


MIN_FREE_DISK_BYTES = 30 * 1024 ** 3  # 30 GB safety margin -- a single VOD can run 20GB+
DISK_SPACE_RECHECK_SECONDS = 120


def free_disk_bytes():
    try:
        return shutil.disk_usage(storage_root()).free
    except OSError:
        return None


def worker_loop():
    while True:
        work_available.wait()
        if downloads_paused:
            time.sleep(1)
            continue
        with lock:
            vid = None
            while queue:
                candidate = queue[0]
                if jobs.get(candidate, {}).get("status") != "queued":
                    queue.pop(0)  # stale entry (canceled, etc.) -- discard and keep looking
                    continue
                vid = candidate
                break
            if not vid:
                work_available.clear()
                continue

        free = free_disk_bytes()
        if free is not None and free < MIN_FREE_DISK_BYTES:
            with lock:
                job = jobs.get(vid)
                if job and job["status"] == "queued":
                    job["error"] = (
                        f"Queued -- not enough disk space to start "
                        f"({free / 1024 ** 3:.1f}GB free, need {MIN_FREE_DISK_BYTES / 1024 ** 3:.0f}GB+). "
                        f"Will keep checking."
                    )
                    save_state()
            time.sleep(DISK_SPACE_RECHECK_SECONDS)
            continue

        with lock:
            if queue and queue[0] == vid:
                queue.pop(0)
            job = jobs.get(vid)
            if job and job.get("error"):
                job["error"] = None
        run_job(vid)


def build_format_args(job):
    fmt = job.get("format", "mp4")
    quality = job.get("quality", "best")
    if fmt == "mp3":
        return ["-x", "--audio-format", "mp3", "--audio-quality", "0"]
    height_filter = f"[height<={quality}]" if quality != "best" else ""
    return [
        "-f",
        f"bv*{height_filter}+ba/b{height_filter}",
        "-S",
        "ext:mp4:m4a",
        "--merge-output-format",
        "mp4",
    ]


def run_job(vid):
    with lock:
        job = jobs[vid]
        category = job.get("category", "auto")
        if category == "manual":
            meta, err = fetch_url_metadata(
                job["url"], job.get("format", "mp4"), job.get("quality", "best")
            )
        elif category == "channel_clip":
            meta, err = fetch_channel_clip_metadata(job["url"], job["channel"], vid)
        else:
            meta, err = fetch_metadata(vid, job["channel"])
        if meta is None:
            job["status"] = "failed"
            job["error"] = err
            save_state()
            return
        job["title"] = meta["title"]
        job["date"] = meta["date"]
        if category == "manual":
            job["uploader"] = meta["uploader"]
            job["site"] = meta["site"]
        elif category == "channel_clip":
            job["game"] = meta["game"]
            job["uploader"] = meta["uploader"]
        else:
            job["game"] = meta["game"]
        os.makedirs(meta["outdir"], exist_ok=True)
        outpath = os.path.join(meta["outdir"], meta["filename_base"] + ".%(ext)s")
        job["outpath"] = outpath
        job["status"] = "downloading"
        job["progress"] = {}
        format_args = build_format_args(job) if category in ("manual", "channel_clip") else []
        save_state()

    proc = subprocess.Popen(
        [YTDLP, "--concurrent-fragments", "8", "--newline", *speed_limit_args(), *format_args, "-o", outpath, meta["url"]],
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        bufsize=1,
        # yt-dlp is itself a Python program; CPython fully buffers stdout
        # (instead of line-buffering) whenever it isn't a real terminal,
        # which a pipe never is. Without this, every progress line sits in
        # yt-dlp's own buffer and only arrives in one burst when the process
        # exits, making the UI look frozen for the entire download and then
        # jump straight to "completed".
        env={**os.environ, "PYTHONUNBUFFERED": "1"},
    )
    with lock:
        job["pid"] = proc.pid

    for line in proc.stdout:
        m = PROGRESS_RE.search(line)
        if m:
            with lock:
                job["progress"] = {
                    "percent": m.group("percent"),
                    "size": m.group("size"),
                    "speed": m.group("speed") or "",
                    "eta": m.group("eta") or "",
                    "frag_done": m.group("frag_done") or "",
                    "frag_total": m.group("frag_total") or "",
                }
        with lock:
            current_status = job["status"]
        if current_status == "canceled":
            proc.kill()
            break

    proc.wait()

    final = None
    with lock:
        job["pid"] = None
        if job["status"] == "canceled":
            cleanup_partial_files(meta["filename_base"], meta["outdir"])
        elif proc.returncode == 0:
            job["status"] = "completed"
            final = find_final_file(meta["filename_base"], meta["outdir"])
            job["final_path"] = final
            job["completed_at"] = datetime.now().isoformat()
            job["progress"] = {"percent": "100"}
        else:
            job["status"] = "failed"
            job["error"] = f"yt-dlp exited {proc.returncode}"
        save_state()

    if final:
        # Read size/duration off the downloaded file itself rather than
        # Twitch's metadata -- it's already local and doesn't depend on the
        # API being reachable or up to date.
        try:
            size_bytes = os.path.getsize(final)
        except OSError:
            size_bytes = None
        duration_seconds = probe_duration_seconds(final)
        with lock:
            job["size_bytes"] = size_bytes
            job["duration_seconds"] = duration_seconds
        save_state()

    fix_permissions()


def find_final_file(base, outdir):
    if not os.path.isdir(outdir):
        return None
    for name in os.listdir(outdir):
        if name.startswith(base) and not any(
            name.endswith(suf) for suf in (".part", ".ytdl", ".temp.mp4")
        ) and ".part-Frag" not in name:
            return os.path.join(outdir, name)
    return None


def cleanup_partial_files(base, outdir):
    if not os.path.isdir(outdir):
        return
    for name in os.listdir(outdir):
        if name.startswith(base):
            try:
                os.remove(os.path.join(outdir, name))
            except OSError:
                pass


def backfill_durations_loop():
    # Runs once per startup so jobs completed before duration_seconds existed
    # (or before a given file was reachable) get it filled in too, not just
    # downloads from here on. Cheap size_bytes is already computed live per
    # request, but duration needs ffprobe, so it's done here once and cached
    # on the job instead of being re-run on every poll.
    with lock:
        todo = [
            (vid, job["final_path"])
            for vid, job in jobs.items()
            if job.get("status") == "completed"
            and job.get("final_path")
            and not job.get("duration_seconds")
        ]
    since_save = 0
    for vid, path in todo:
        if not os.path.isfile(path):
            continue
        duration = probe_duration_seconds(path)
        if duration is None:
            continue
        with lock:
            job = jobs.get(vid)
            if job is not None:
                job["duration_seconds"] = duration
        since_save += 1
        if since_save >= 5:
            save_state()
            since_save = 0
        time.sleep(0.2)
    if since_save:
        save_state()


def backfill_thumbnails_loop():
    # Same idea as backfill_durations_loop, for jobs that existed before
    # local thumbnail caching did -- otherwise only newly-discovered jobs
    # ever get cached, leaving every already-tracked job (the ones most at
    # risk of Twitch having already deleted their source) permanently
    # dependent on a remote CDN URL that may already be gone.
    with lock:
        todo = [(vid, job.get("thumbnail")) for vid, job in jobs.items() if job.get("thumbnail")]
    for vid, url in todo:
        if os.path.exists(thumbnail_path(vid)):
            continue
        cache_thumbnail(vid, url)
        time.sleep(0.2)


def pause_job(vid):
    # Windows has no equivalent of SIGSTOP for suspending an arbitrary
    # process without extra dependencies (e.g. psutil) -- a job already
    # downloading there just runs to completion instead; Pause All still
    # stops the *next* one from starting via the global flag.
    if IS_WINDOWS:
        return False
    with lock:
        job = jobs.get(vid)
        if not job or job["status"] != "downloading" or not job["pid"]:
            return False
        try:
            os.kill(job["pid"], signal.SIGSTOP)
        except ProcessLookupError:
            return False
        job["status"] = "paused"
        save_state()
        return True


def resume_job(vid):
    if IS_WINDOWS:
        return False
    with lock:
        job = jobs.get(vid)
        if not job or job["status"] != "paused" or not job["pid"]:
            return False
        try:
            os.kill(job["pid"], signal.SIGCONT)
        except ProcessLookupError:
            return False
        job["status"] = "downloading"
        save_state()
        return True


