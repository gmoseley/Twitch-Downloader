    def serve_download(self, vid):
        with lock:
            job = jobs.get(vid)
            path = job.get("final_path") if job and job.get("status") == "completed" else None
        if not path or not os.path.isfile(path):
            self._json({"error": "not available"}, 404)
            return
        self.stream_file(path)

    def serve_thumbnail(self, vid):
        path = thumbnail_path(vid)
        if not os.path.isfile(path):
            self.send_response(404)
            self.end_headers()
            return
        with open(path, "rb") as f:
            data = f.read()
        self.send_response(200)
        self.send_header("Content-Type", "image/jpeg")
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "public, max-age=86400")
        self.end_headers()
        self.wfile.write(data)

    def stream_file(self, path):
        file_size = os.path.getsize(path)
        filename = os.path.basename(path)
        ctype = mimetypes.guess_type(filename)[0] or "application/octet-stream"

        start, end = 0, file_size - 1
        status = 200
        range_header = self.headers.get("Range")
        if range_header:
            m = re.match(r"bytes=(\d*)-(\d*)", range_header)
            if m and (m.group(1) or m.group(2)):
                if m.group(1):
                    start = int(m.group(1))
                if m.group(2):
                    end = min(int(m.group(2)), file_size - 1)
                status = 206

        length = end - start + 1
        quoted = urllib.parse.quote(filename)

        self.send_response(status)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(length))
        self.send_header("Accept-Ranges", "bytes")
        self.send_header(
            "Content-Disposition", f"attachment; filename*=UTF-8''{quoted}"
        )
        self.send_header("Cache-Control", "no-store")
        if status == 206:
            self.send_header("Content-Range", f"bytes {start}-{end}/{file_size}")
        self.end_headers()
        self.wfile.flush()

        try:
            with open(path, "rb") as f:
                out_fd = self.connection.fileno()
                in_fd = f.fileno()
                offset = start
                remaining = length
                use_sendfile = hasattr(os, "sendfile")  # not available on Windows
                while remaining > 0:
                    if use_sendfile:
                        try:
                            sent = os.sendfile(out_fd, in_fd, offset, min(remaining, 8 * 1024 * 1024))
                        except OSError:
                            use_sendfile = False
                            f.seek(offset)
                            continue
                        if sent == 0:
                            break
                        offset += sent
                        remaining -= sent
                    else:
                        chunk = f.read(min(1024 * 1024, remaining))
                        if not chunk:
                            break
                        self.wfile.write(chunk)
                        remaining -= len(chunk)
        except (BrokenPipeError, ConnectionResetError):
            pass

    def _read_json(self):
        length = int(self.headers.get("Content-Length", 0) or 0)
        if not length:
            return {}
        try:
            return json.loads(self.rfile.read(length))
        except (json.JSONDecodeError, UnicodeDecodeError):
            return {}

