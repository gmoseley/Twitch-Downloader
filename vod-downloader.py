# Thumbnails are cached to disk the moment a job is discovered, instead of
# just linking the frontend straight to Twitch's CDN copy -- Twitch deletes a
# VOD's (and eventually a clip's) source and thumbnail after it ages out, so
# a job that's still sitting in the library would otherwise end up with a
# broken image once that happens. Best-effort and fire-and-forget: a failed
# fetch just leaves nothing cached, which the serving route falls back on.
