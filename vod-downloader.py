def cancel_job(vid):
    with lock:
        job = jobs.get(vid)
        if not job:
            return False
        if job["status"] in ("completed", "failed", "canceled"):
            return False
        if job["status"] == "queued":
            if vid in queue:
                queue.remove(vid)
            job["status"] = "canceled"
            save_state()
            return True
        job["status"] = "canceled"
        pid = job["pid"]
    if pid:
        try:
            if IS_WINDOWS:
                os.kill(pid, signal.SIGTERM)  # maps to TerminateProcess on Windows
            else:
                os.kill(pid, signal.SIGCONT)  # wake it first in case it was paused
                os.kill(pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
    return True


