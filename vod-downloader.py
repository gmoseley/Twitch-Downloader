def fetch_full_item_metadata(url):
    try:
        meta = subprocess.run([YTDLP, "-J", url], capture_output=True, text=True, timeout=30)
    except subprocess.TimeoutExpired:
        return None
    if meta.returncode != 0:
        return None
    try:
        d = json.loads(meta.stdout)
    except json.JSONDecodeError:
        return None
    title = sanitize(d.get("title"))
    cats = d.get("categories") or []
    # Clips carry a single "categories" entry; VODs don't -- they fall back to
    # whichever game occupied the most airtime according to stream chapters.
    category = cats[0] if cats else primary_game(d.get("chapters"))
    if category == "Unknown":
        category = ""
    creator = d.get("uploader") or ""
    thumbnail = d.get("thumbnail") or ""
    return {"title": title, "category": category, "creator": creator, "thumbnail": thumbnail}


def get_or_cache_item(video_id, url, kind=""):
    """Returns (data, was_cached). Fetches + permanently caches on a miss."""
    cached = get_cached_channel_item(video_id)
    if cached:
        return cached, True
    data = fetch_full_item_metadata(url)
    if data is None:
        return None, False
    cache_channel_item(video_id, kind=kind, **data)
    return data, False


def warm_channel_cache(channel):
    """Background sweep: fetch + cache title/category/creator/thumbnail for
    every VOD and clip on a channel, not just whatever a given search's scope
    covered. Runs as a plain daemon thread, detached from any HTTP request --
    a client canceling their search or the panel just being closed doesn't
    stop it; it keeps going, even for hours, until the whole channel is
    cached. Safe to call repeatedly: already-cached items are skipped, and a
    channel already being warmed is not warmed twice concurrently."""
    with warming_channels_lock:
        if channel in warming_channels:
            return
        warming_channels.add(channel)
    try:
        listings = [
            ("vod", f"https://www.twitch.tv/{channel}/videos?filter=archives&sort=time"),
            ("clip", f"https://www.twitch.tv/{channel}/clips?filter=clips&range=all"),
        ]
        candidates = []
        for kind, listing_url in listings:
            try:
                out = subprocess.run(
                    [YTDLP, "--flat-playlist", "-J", listing_url],
                    capture_output=True, text=True, timeout=90,
                )
            except subprocess.TimeoutExpired:
                continue
            if out.returncode != 0:
                continue
            try:
                data = json.loads(out.stdout)
            except json.JSONDecodeError:
                continue
            for e in data.get("entries", []) or []:
                vid = e.get("id")
                if not vid or get_cached_channel_item(vid):
                    continue
                if kind == "clip":
                    item_url = e.get("url") or f"https://www.twitch.tv/{channel}/clip/{vid}"
                else:
                    item_url = e.get("url") or f"https://www.twitch.tv/videos/{vid.lstrip('v')}"
                candidates.append((vid, item_url, kind))

        def warm_one(item):
            vid, item_url, kind = item
            if get_cached_channel_item(vid):
                return
            get_or_cache_item(vid, item_url, kind)

        with ThreadPoolExecutor(max_workers=CHANNEL_CACHE_WARM_WORKERS) as pool:
            list(pool.map(warm_one, candidates))
    finally:
        with warming_channels_lock:
            warming_channels.discard(channel)


def probe_duration_seconds(path):
    try:
        out = subprocess.run(
            [
                "ffprobe", "-v", "error",
                "-show_entries", "format=duration",
                "-of", "default=noprint_wrappers=1:nokey=1",
                path,
            ],
            capture_output=True, text=True, timeout=30,
        )
        return float(out.stdout.strip())
    except (subprocess.TimeoutExpired, ValueError, OSError):
        return None


