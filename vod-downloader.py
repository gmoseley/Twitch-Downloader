def channel_retention_cutoff_ts(channel):
    """None means no age limit -- everything found gets auto-downloaded."""
    days = channel_retention_days(channel)
    if not days:
        return None
    return time.time() - days * 86400


def update_channel(name, interval_hours=None, retention_days=None):
    with channels_lock:
        if name not in channels:
            return False
        if interval_hours is not None:
            channels[name]["interval_hours"] = max(MIN_CHANNEL_INTERVAL_HOURS, min(MAX_CHANNEL_INTERVAL_HOURS, int(interval_hours)))
        if retention_days is not None:
            channels[name]["retention_days"] = max(MIN_RETENTION_DAYS, min(MAX_RETENTION_DAYS, int(retention_days)))
    save_channels()
    return True


def channel_scanner_loop():
    while True:
        time.sleep(CHANNEL_SCAN_TICK_SECONDS)
        now = time.time()
        due = []
        with channels_lock:
            for name, info in channels.items():
                if info.get("next_check_at", 0) <= now:
                    due.append(name)
        for name in due:
            try:
                scan_for_new_vods(name)
            except Exception:
                pass
            try:
                scan_for_new_clips(name)
            except Exception:
                pass
            with channels_lock:
                info = channels.get(name)
                if info is not None:
                    interval_hours = info.get("interval_hours", DEFAULT_CHANNEL_INTERVAL_HOURS)
                    info["next_check_at"] = time.time() + interval_hours * 3600
            save_channels()
        try:
            purge_old_clips()
        except Exception:
            pass


