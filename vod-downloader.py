def list_dir(path):
    # Backs the "Browse..." folder picker for the storage root. A real
    # native file-picker dialog isn't something a plain web page can open on
    # the admin's machine -- this instead browses the filesystem of whatever
    # machine the server itself runs on, which is what actually matters for
    # picking a storage path (and is the only path structure the server can
    # even validate). LAN/private-IP gated like everything else here.
    real = os.path.realpath(path) if path else os.path.abspath(os.sep)
    if not os.path.isdir(real):
        return None
    try:
        names = sorted(
            name for name in os.listdir(real)
            if not name.startswith(".") and os.path.isdir(os.path.join(real, name))
        )
    except OSError:
        names = []
    entries = [{"name": name, "path": os.path.join(real, name)} for name in names]
    _drive, _tail = os.path.splitdrive(real)
    is_root = _tail in ("", os.sep)
    parent = None if is_root else os.path.dirname(real.rstrip(os.sep))
    return {"path": real, "parent": parent, "entries": entries}


