def load_state():
    os.makedirs(STATE_DIR, exist_ok=True)
    # Jobs from before multi-channel support was added predate the "channel"
    # field; VOD_CHANNEL (now otherwise unused) is read here only to backfill
    # it on those old records so they keep showing up once that channel is
    # re-added as a tracked channel.
    legacy_channel = os.environ.get("VOD_CHANNEL", "").strip()
    migrated = False
    if os.path.exists(STATE_FILE):
        with open(STATE_FILE) as f:
            data = json.load(f)
        for vid, job in data.items():
            if job["status"] in ("downloading", "paused"):
                job["status"] = "queued"
                job["progress"] = {}
            job["pid"] = None
            # Migration: jobs predating the "category" field (from before the
            # manual/search tabs existed) were always auto-channel VOD downloads.
            if "category" not in job:
                job["category"] = "auto"
                migrated = True
            if job["category"] in ("auto", "channel_clip") and not job.get("channel"):
                job["channel"] = legacy_channel
                migrated = True
            jobs[vid] = job
    for vid, job in jobs.items():
        if job["status"] == "queued":
            queue.append(vid)
    if queue:
        work_available.set()
    # Persist the migration immediately -- it only reads VOD_CHANNEL from the
    # environment, which is expected to be removed once this channel is
    # re-added as a tracked channel, so the backfilled "channel" field must
    # land on disk now rather than being redone (with nothing left to backfill
    # from) on the next restart.
    if migrated and legacy_channel:
        save_state()


def save_state():
    tmp = STATE_FILE + ".tmp"
